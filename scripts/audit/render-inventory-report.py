#!/usr/bin/env python3
"""Render AUDIT_REPORTS/RESOURCE_OPTIMIZATION_QUERY_INVENTORY_FINAL.md from two query-inventory.mjs JSON outputs.
usage: render-inventory-report.py head.json base.json out.md"""
import json, collections, sys
h = json.load(open(sys.argv[1])); b = json.load(open(sys.argv[2])); out = sys.argv[3]

def cls(r):
    if r['method'] == 'aggregate': return 'AGG (pipeline; check $group/$match shape)'
    if r['isExport']: return 'C-export: complete dataset REQUIRED'
    if r['isCronOrBackground']: return 'E-background/batch: cursor/stream, not offset paging'
    if r['inMemoryAggregationPattern']: return 'D-aggregation candidate (in-memory sum/loop over result)'
    if r['httpMethod'] == 'GET' and not r['pagingParamsInFunction']: return 'A-user list, NO paging params: pagination candidate'
    if r['httpMethod'] == 'GET': return 'A2-GET already reads paging params (secondary lookup or paged via helper)'
    if r['isHttpHandler']: return 'F-write handler lookup (bounded by request)'
    return 'G-helper/shared lib'

def st(d):
    a = [r for r in d if r['file'].startswith('app/api')]
    f = [r for r in a if r['method'] == 'find']; g = [r for r in a if r['method'] == 'aggregate']
    return len(f), sum(not r['hasLimit'] for r in f), len(g), sum(not r['hasLimit'] for r in g)

api = [r for r in h if r['file'].startswith('app/api') and not r['hasLimit']]
lib = [r for r in h if r['file'].startswith('lib') and not r['hasLimit']]
c = collections.Counter(cls(r) for r in api)
sb, sh = st(b), st(h)
nonetenant = [r for r in api if r['method'] == 'find' and r['tenantScoping'] == 'NONE FOUND']

md = f"""# Resource Optimization — Final Query Inventory (G2)

Generated by `scripts/audit/query-inventory.mjs` (TypeScript-AST based; resolves model aliases through `models/` imports, follows multi-line chains, inspects the enclosing function) and rendered by `scripts/audit/render-inventory-report.py`.
Re-run: `node scripts/audit/query-inventory.mjs . > head.json` (and the same on a `git archive` of the base commit).

## Status: **INCOMPLETE** — the inventory is complete; only a slice of the implementation is done

| Scope: `app/api/**` | base `f38af917` | this branch |
|---|---|---|
| `Model.find(...)` calls | {sb[0]} | {sh[0]} |
| …with no `.limit()` in the chain | {sb[1]} | **{sh[1]}** |
| `Model.aggregate(...)` calls | {sb[2]} | {sh[2]} |
| …with no `$limit` (most are `$group` reports and are fine) | {sb[3]} | {sh[3]} |
| `lib/**` unbounded `find`/`aggregate` (outside the original 298 scope) | — | {len(lib)} |

### Reconciling 298 / 266 / this scan
- **298** (baseline report): produced by an unsaved script; no per-query list exists, so it cannot be reproduced or diffed.
- **266** (earlier audit): regex over `Capitalised.find(` with no limit in a ~900-character window.
- **{sh[1]}** unbounded `find` (+ **{sh[3]}** unbounded `aggregate`) now: AST-based and reproducible. The counts differ because the regex counted aliased/non-DB `.find` on capitalised identifiers and missed `.limit()` placed after a line break, and `aggregate` is counted separately here. None of the three equals the others; only this one can be re-run.

## Classification of the {len(api)} unbounded calls in `app/api` (static signals; needs human confirmation)
| Class | Count |
|---|---|
""" + "\n".join(f"| {k} | {v} |" for k, v in sorted(c.items())) + f"""

Tenant-scoping signal (query argument / variable / enclosing-function text mentions tenant): {len(nonetenant)} `find` calls show none. Each was inspected: all are intentional platform-admin or cron cross-tenant reads (`Organization`, `SaaSSubscription`, `BillingPayment`, `SubscriptionEvent`, `Plan`, `RetentionPolicy`; the billing ones are now aggregations). This is a **signal, not a proof**: the other calls were not individually traced through their authorization path.

## What was implemented on `feature/resource-optimization-remediation`
| Item | Change | Evidence |
|---|---|---|
| `lib/api/pagination.ts` | Opt-in keyset (cursor) helper; `_id` tie-break; max page 100; invalid input → 400 | `tests/resourceOptimization/keysetPagination.test.ts` |
| `GET /api/projects` | Uses it **only when `?limit`/`?cursor` is sent**; with no params the complete legacy response is unchanged (dashboard KPIs and list page untouched) | same file: compat, ordering, tenant isolation, RBAC, concurrent insert |
| `GET /api/platform/billing/overview` | 5 full-collection loads + 6 counts → 3 aggregations + 2 counts; half-up rounding and `||` truthiness preserved exactly | `billingOverviewParity.test.ts` (old logic as oracle) |
| `connectBaseDB` | Adopted by the public waitlist POST only; proven not to register the model registry; single shared connection | `connectBaseDB.test.ts` |

## NOT implemented (remaining G2 work)
- **Default pagination** for every user-facing list. Each needs its consumers migrated (tables, dashboards that compute KPIs from the full array, exports, hooks, `cachedFetch` prefetchers). Adopting the helper elsewhere without that migration saves nothing; flipping a default without it breaks the UI. Suggested order: (1) endpoints whose only consumer is a table, (2) dashboards → server-side aggregates, (3) flip defaults.
- **Aggregation** for the remaining D-class candidates (one converted); each needs a parity test against the old arithmetic.
- **Cursor/stream** for class E (cron/migration/worker). Class C (exports) stay complete by design.
- **Indexes**: none added; a per-endpoint sort/filter review must precede any (e.g. `BillingPayment` is indexed on `{{status,type,createdAt}}` while the overview filters `createdAt` first).
- Columns that cannot be derived statically — business purpose, expected dataset size, UI clients, proposed implementation per query, test requirements — are **not filled in** and require human review. This document is not sign-off for those.

## Unbounded calls in `app/api` (no `.limit()` / `$limit` in the chain)
| # | File:line | Model | Method | Handler | Class | Tenant signal | Reads paging params |
|---|---|---|---|---|---|---|---|
"""
rows = [f"| {i} | `{r['file']}:{r['line']}` | {r['model']} | {r['method']} | {r['fn']} | {cls(r)} | {r['tenantScoping']} | {'yes' if r['pagingParamsInFunction'] else 'no'} |"
        for i, r in enumerate(sorted(api, key=lambda r: (r['file'], r['line'])), 1)]
open(out, "w").write(md + "\n".join(rows) + "\n")
print(len(api), dict(c), sb, sh)
